"""
cloud/storage/base.py - Abstract Base Class for Pluggable Cloud Storage Adapters.

Defines the contract required by CloudServer for device management, CRDT LWW mutation application,
delta pull queries, and health/status reporting.
"""

from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional, Tuple


class BaseStorageAdapter(ABC):
    """
    Pluggable storage adapter interface for Neko Cloud Server.
    Implemented by SQLiteStorageAdapter (local/dev/test) and PostgresStorageAdapter (production/Supabase).
    """

    @property
    @abstractmethod
    def adapter_name(self) -> str:
        """Returns the human-readable identifier of the storage adapter."""
        pass

    @abstractmethod
    def initialize(self) -> None:
        """Initializes database connections, schemas, tables, and indices."""
        pass

    @abstractmethod
    def register_device(
        self,
        device_id: str,
        device_name: str,
        client_version: str,
        token_hash: str
    ) -> bool:
        """
        Registers or updates a client workstation record in the database.
        Returns True on success.
        """
        pass

    @abstractmethod
    def authenticate_device(self, device_id: str, token: str) -> bool:
        """
        Verifies that the provided raw token matches the stored SHA-256 hash for device_id.
        Returns True if authenticated, False otherwise.
        """
        pass

    @abstractmethod
    def apply_mutation(self, mutation: Dict[str, Any]) -> Tuple[bool, int]:
        """
        Evaluates and applies a mutation under 3-tier CRDT LWW rules:
        1. Higher timestamp wins.
        2. On timestamp equality, tombstone (deleted=True) wins.
        3. On deleted equality, canonical JSON tie-breaking wins.

        Returns: (applied: bool, server_sequence: int).
        If the mutation is rejected as stale or idempotent duplicate, returns (False, current_server_sequence).
        """
        pass

    @abstractmethod
    def pull_mutations(
        self,
        since_sequence: int,
        exclude_device: Optional[str] = None
    ) -> Tuple[List[Dict[str, Any]], int]:
        """
        Queries all mutations where server_sequence > since_sequence.
        Optionally filters out mutations generated by exclude_device.

        Returns: (mutations: List[Dict], max_server_sequence: int).
        If no mutations match, max_server_sequence equals max(since_sequence, 0).
        """
        pass

    @abstractmethod
    def get_status(self) -> Dict[str, Any]:
        """
        Returns telemetry dictionary containing:
        - server_sequence: int
        - active_entities: int
        - active_devices: int
        - adapter: str
        - status: str ("healthy" or "ok")
        """
        pass

    def close(self) -> None:
        """Optional resource cleanup hook."""
        pass
